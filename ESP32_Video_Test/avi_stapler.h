void add_frame(File &file, uint8_t *buf, size_t len) {
  uint8_t padding = len % 2;
  uint32_t frame_size = len + padding;
  uint32_t total_chunk_size = 8 + len + padding;

  uint8_t *chunk_buffer = (uint8_t*) heap_caps_malloc(total_chunk_size, MALLOC_CAP_SPIRAM);
  
  if (chunk_buffer == NULL) {
    Serial.println("PSRAM Buffer failed! Defaulting to slow writes.");
    uint8_t frame_header[8] = {0x30, 0x30, 0x64, 0x63, (uint8_t)(frame_size & 0xFF), (uint8_t)((frame_size >> 8) & 0xFF), (uint8_t)((frame_size >> 16) & 0xFF), (uint8_t)((frame_size >> 24) & 0xFF)};
    file.write(frame_header, 8);
    file.write(buf, len);
    if (padding) { uint8_t pad_byte = 0x00; file.write(&pad_byte, 1); }
    movi_size += total_chunk_size;
    return;
  }

  chunk_buffer[0] = 0x30; chunk_buffer[1] = 0x30; chunk_buffer[2] = 0x64; chunk_buffer[3] = 0x63;
  chunk_buffer[4] = frame_size & 0xFF;
  chunk_buffer[5] = (frame_size >> 8) & 0xFF;
  chunk_buffer[6] = (frame_size >> 16) & 0xFF;
  chunk_buffer[7] = (frame_size >> 24) & 0xFF;

  memcpy(&chunk_buffer[8], buf, len);

  if (padding) {
    chunk_buffer[8 + len] = 0x00;
  }

  file.write(chunk_buffer, total_chunk_size);
  free(chunk_buffer);
  movi_size += total_chunk_size;
}

void end_avi(File &file, int frames) {
  uint32_t file_size = movi_size + 324 - 8;
  
  file.seek(4);
  file.write((uint8_t*)&file_size, 4);

  file.seek(48);
  file.write((uint8_t*)&frames, 4);
  file.seek(140);
  file.write((uint8_t*)&frames, 4);

  file.seek(320);
  file.write((uint8_t*)&movi_size, 4);
  
  file.close();
}